test("CLI keeps stdout free of SDK diagnostics in JSON stdout mode", () => {
  const fixtureDir = fs.mkdtempSync(
    path.join(os.tmpdir(), "weighin-cli-stdout-"),
  );
  const cwd = fs.mkdtempSync(path.join(os.tmpdir(), "weighin-cli-cwd4-"));
  try {
    sdkFixturesTree(fixtureDir, cargoLock("28.0.0"));
    const r = spawnSync(
      process.execPath,
      [
        bin,
        path.join(fixtureDir, "weighin-fixtures.json"),
        "--rpc-url",
        "http://127.0.0.1:1",
        "--json-stdout",
      ],
      { cwd, encoding: "utf8", timeout: 8000 },
    );
    assert.equal(r.signal, "SIGTERM", r.stdout + r.stderr);
    // stdout carries the JSON payload only; diagnostics belong on stderr.
    assert.equal(r.stdout, "");
    assert.match(r.stderr, /SDK .*28\.0\.0 \(lock: .*contract\/Cargo\.lock\)/);
    assert.match(r.stderr, /SDK:\s+28\.0\.0/);
  } finally {
    fs.rmSync(fixtureDir, { recursive: true, force: true });
    fs.rmSync(cwd, { recursive: true, force: true });
  }
});
